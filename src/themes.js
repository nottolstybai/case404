//
// places: loc — где? (в подвале), to — куда? (в подвал). Названия не длиннее 9 букв — иначе не влезут в кнопку.
// items:  acc — что? (верёвку).
// intros: body: false — жертва пропала, тела нет; тогда главные улики про «орудие» не подходят.
// main:   главная улика по категории; body: true — подразумевает, что тело нашли.
// skipRoles — кого из подозреваемых не бывает в этом месте.

const cap = (t) => t[0].toUpperCase() + t.slice(1);

